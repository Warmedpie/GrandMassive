// Nnue.h : neural network evaluation (NNUE) for GrandMassive.
//
// Architecture: (768 -> H) x 2 -> 1, "perspective" net.
//   Inputs: 768 = 2 colours (own / enemy, relative to the perspective) x
//   6 piece types x 64 squares (mirrored vertically for Black's perspective).
//   One accumulator per perspective: b1 + sum of W1 rows of the active
//   features, updated incrementally as pieces are placed / removed.
//   Activation: SCReLU, clamp(x, 0, 1)^2.
//   Output: W2 . [side to move's accumulator, other side's accumulator] + b2,
//   times OutputScale = centipawns.
//
// Quantization (the trainer, tools/nnue_train.cpp, works in floats):
//   W1, b1 x QA (int16), W2 x QB (int16), b2 x QA*QA*QB (int32).
//   t = clamp(acc, 0, QA)^2 / 2 (fits int16), sum = sum(t * W2) (int32 lanes)
//   eval = (2 * sum + b2) * OutputScale / (QA * QA * QB)
// Weights are clipped to +-1.98 in training: |W2| <= 1014, and a 32-bit
// lane (32 pairs of products) stays below 2^31.
//
// The network weights live in NetData.h (generated by the trainer).
//
// Net 1 (bootstrap): trained on 8.1M quiet positions from self-play of the
// hand-written-eval engine (tools/datagen, 8000 nodes/move, Wide-book
// openings), labelled with the search score only (lam 1.0: blending in the
// game result was much worse with this little data: lam 0.5 -212, 0.9 -109
// on 2M positions), 25 epochs. Data scaling vs. the HCE engine: 2M ~-30,
// 5.2M +6, 8.1M +45. Net 1 vs. the HCE engine: @25 ms +262 -185 =153 (+45),
// @100 ms +238 -174 =188 (+37), 4s+40ms clock +157 -107 =136 (+44), 600 /
// 600 / 400 games, LOS 100%. Build with AVX2 (GM_NATIVE): the plain-C++
// fallback runs at ~60% of the speed.
//
// Net 10 (current NetData.h): net 9's layout (512 wide, 8 output buckets,
// lam 1.0, 25 epochs) on the same 419.0M positions, all relabeled at 32k nodes
// by the net-9 engine (tools/relabel; before: 8k labels from whichever engine
// played them, HCE through net 7). Val loss 0.005149 (not comparable with net
// 9's: different targets); train/val gap 1.8% at epoch 25, still improving
// every epoch. vs. net 9, same search, 10+0.1: SPRT [0, 5] H1 after 286 games,
// +82 =164 -40, +51.4 +-18.2 Elo. Adopted Oct 11 2026. Bench 251019. Net 9
// kept as tools/data/NetData_net9.h (and NetData_prev.h).
//
// Net 9: 512 hidden neurons (NNUE_HIDDEN default 256 ->
// 512), trained on net 8's data (417.7M positions), 8 output buckets, lam 1.0,
// 25 epochs, val loss 0.004317 (net 8, 256 wide, same data: 0.004696, -8.1%;
// doubling the data had given the 256 net -2.7%). evalcheck vs. Stockfish
// labels: endgame set -4.3%, mixed -5.3%, attack -5.3% (pawn endings -10%).
// Speed: bench nodes/s about -8% (lazy accumulator). vs. net 8, same search,
// 10+0.1: SPRT [0, 5] H1. Adopted Oct 2026. Bench 257727 (RepRule 1, same
// bench as RepRule 0). Net 8 kept as tools/data/NetData_net8.h.
//
// Net 8: 417.7M positions: the net-7 data + 213.6M from self-play of the
// net-7 engine (gen_nn7_20261006_*), 256 wide, 8 output buckets, lam 1.0, 25
// epochs, val loss 0.004696. Adopted (vs. net 7, same search, 10+0.1). Bench
// 266802. Kept as tools/data/NetData_net8.h.
//
// Net 7: 204.0M positions: the net-6 data + 65M from
// self-play of the net-6 engine with the audited search (gen_nn6_20261005_*;
// known endings adjudicated, mate scores clamped to 2000; the trainer drops
// known-ending positions), 8 output buckets, lam 1.0, 25 epochs (best: 25),
// val loss 0.00483 (other validation set than net 6's). Evals: scale vs.
// net 6 1.02, correlation 0.996 (1500 positions). vs. net 6, same search,
// 10+0.1: about +13 Elo when stopped (+6 +- 14 after 560 games), adopted.
// Bench 262010.
//
// Net 6: 138.8M positions: the net-5 data + 74.6M from
// self-play of the net-5 engine (gen_nn5_*), 8 output buckets, lam 1.0, 25
// epochs, val loss 0.00473. vs. net 5 @25 ms: +223 -124 =253 (600 games,
// ~+58, LOS 100%).
//
// Net 5: 64.2M positions: the net-4 data + 22.6M from
// self-play of the net-4 engine (gen_nn4_*), 8 output buckets, lam 1.0, 25
// epochs, val loss 0.00496 (1-bucket version on the same data: 0.00506).
// vs. net 4 @25 ms: +214 -140 =246 (600 games, ~+43, LOS 100%).
//
// Net 4: 41.6M positions: the net-3 data + 15.5M from
// self-play of the net-3 engine (generated and trained on the developer's
// PC with tools/gen_data.bat / train_net.bat), lam 1.0, 25 epochs, val loss
// 0.00525. vs. net 3 @25 ms: +228 -141 =231 (600 games, ~+51, LOS 100%).
//
// Net 3: 26.1M positions: the net-2 data + 10.0M from
// self-play of the net-2 engine (with SPSA round-3 search), lam 1.0, 25
// epochs. vs. net 2 (same search) @25 ms: +253 -138 =209 (600, ~+67). Trained
// without the 8.1M HCE-era positions (18.2M): -17 vs. this net (600 games),
// so the oldest data still helps.
//
// Net 2: same architecture, trained on 16.3M positions:
// the 8.1M above + 8.2M from self-play of the net-1 engine (same datagen
// settings), lam 1.0, 25 epochs. vs. net 1 @25 ms: +270 -128 =202 (600
// games, ~+84, LOS 100%). Trained on the 8.2M net-1 positions alone: +39.
//
// Output buckets (NNUE_OUT_BUCKETS, default 8 since net 5; 1 = none): that many output layers
// (w2, b2), one chosen per position by the number of pieces on the board
// (bucket = (pieces - 2) / ceil(32 / buckets)), so e.g. endgames get their own
// output weights. Must match the trainer's setting (and NetData.h's size).
// First test: 8 buckets on the net-4 data (41.6M): val loss 0.00513 vs
// 0.00525, vs. net 4 @25 ms +181 -170 =249 (600 games, ~+6, LOS 72%). Gen-5
// data (64.2M), 8 vs 1 bucket head to head: +190 -164 =246 (~+15, LOS 92%):
// adopted with net 5.
//
// King buckets (NNUE_KING_BUCKETS, default 1 = none): the first layer has
// that many copies of its 768 input rows; each perspective uses the copy for
// its own king's square (KingBucketMap), and with more than 1 bucket the
// board is also mirrored left-right for a perspective whose king is on files
// e-h, so the map only covers files a-d. When a king moves to another bucket
// or across the d/e line, that perspective's accumulator is rebuilt from the
// board (Accumulator::refresh_side); the other side's is unaffected. Trained
// with a factorizer (tools/nnue_train.cpp), merged into the buckets at export.
// First test (4 buckets, net-6 data, 25 epochs): vs. net 6 -3 and, with the
// accumulator cache, -4 (600 games each). Loss on new games (not trained on):
// net 6 0.00476, 4 buckets 25 epochs 0.00482, 10 epochs 0.00486 (plain net
// 10 epochs 0.00496): the buckets fit the training games faster than they
// generalize at 139M positions; 25 epochs beat 10 for both. Not adopted: re-test
// with more data, comparing held-out validation loss first.
//
// EV_NNUE (Eval.h) selects the evaluation at compile time: 1 = this network
// (default), 0 = the hand-written eval.

